const BY_CODE: ReadonlyMap<string, EmojiEntry> = new Map(EMOJI.map((entry) => [entry.code, entry]));

export function groupEntries(group: EmojiGroup): EmojiEntry[] {
  return EMOJI.filter((entry) => entry.group === group);
}

/**
 * `:+1:` → 👍. Accepts the code with or without the colons, and any alias.
 * Returns undefined for anything unknown, so callers can leave the text alone.
 */
export function emojiForShortcode(code: string): string | undefined {
  const bare = code.trim().replace(/^:/, "").replace(/:$/, "").toLowerCase();
  if (!bare) return undefined;
  const canonical = ALIASES[bare] ?? bare;
  return BY_CODE.get(canonical)?.char;
}

/**
 * Search by code and keywords, Korean or English, case-insensitive.
 *
 * Ranking is deliberately simple and stable: code prefix matches first, then
 * a keyword that starts with the query, then any substring match — each tier
 * preserving data order so the same query always gives the same list.
 */
export function searchEmoji(query: string, limit = 24): EmojiEntry[] {
  const needle = query.trim().toLowerCase().replace(/^:/, "");
  if (!needle) return [];

  const tiers: EmojiEntry[][] = [[], [], []];
  for (const entry of EMOJI) {
    if (entry.code.startsWith(needle)) {
      tiers[0]?.push(entry);
      continue;
    }
    const keywords = entry.keywords;
    if (keywords.some((keyword) => keyword.toLowerCase().startsWith(needle))) {
      tiers[1]?.push(entry);
      continue;
    }
    if (
      entry.code.includes(needle) ||
      keywords.some((keyword) => keyword.toLowerCase().includes(needle))
    ) {
      tiers[2]?.push(entry);
    }
  }

  // Aliases are searchable too: `:thumbsup` should find 👍 even though the
  // canonical code is `+1`. Alias hits rank with code-prefix hits.
  const aliased: EmojiEntry[] = [];
  for (const [alias, canonical] of Object.entries(ALIASES)) {
    if (alias.startsWith(needle)) {
      const entry = BY_CODE.get(canonical);
      if (entry) aliased.push(entry);
    }
  }

  const seen = new Set<string>();
  const out: EmojiEntry[] = [];
  for (const entry of [...(tiers[0] ?? []), ...aliased, ...(tiers[1] ?? []), ...(tiers[2] ?? [])]) {
    if (seen.has(entry.code)) continue;
    seen.add(entry.code);
    out.push(entry);
    if (out.length >= limit) break;
  }
  return out;
}

/**
 * Replace `:code:` with the emoji, outside code spans only.
 *
 * The token needs a non-word, non-colon boundary on both sides so `10:30`,
 * `http://x`, `a:b:c` and `key:value` never turn into emoji. Unknown codes
 * are left exactly as typed.
 */
export function replaceShortcodes(text: string): string {
  if (!text.includes(":")) return text;

  // Code spans are lifted out behind a sentinel that cannot come from a
  // textarea (a NUL, built at runtime so no editor can strip it). A
  // space-padded number would collide with real text such as "회의 10 시".
  const spans: string[] = [];
  const stashed = text.replace(/```[\s\S]*?```|`[^`\n]+`/g, (match) => {
    spans.push(match);
    return `${SENTINEL}${spans.length - 1}${SENTINEL}`;
  });

  const replaced = stashed.replace(
    /(^|[^\w:]):([a-z0-9_+-]{1,64}):(?=$|[^\w:])/gimu,
    (match, before: string, code: string) => {
      const emoji = emojiForShortcode(code);
      return emoji ? `${before}${emoji}` : match;
    },
  );

  return replaced.replace(
    new RegExp(`${SENTINEL}(\\d+)${SENTINEL}`, "g"),
    (_m, index: string) => spans[Number(index)] ?? "",
  );
}

function readRecent(): string[] {
  try {
    const raw = window.localStorage.getItem(RECENT_KEY);
    if (!raw) return [];
    const parsed: unknown = JSON.parse(raw);
    return Array.isArray(parsed)
      ? parsed.filter((item): item is string => typeof item === "string" && item.length > 0)
      : [];
  } catch {
    return [];
  }
}

/** Most recently used first. Falls back to a workplace default set. */
export function recentEmoji(limit = 16): string[] {
  const stored = readRecent();
  const source = stored.length > 0 ? stored : DEFAULT_RECENT;
  return source.slice(0, limit);
}

/** Move-to-front, de-duplicated, capped. Storage failures are ignored. */
export function noteEmojiUse(char: string): void {
  if (!char) return;
  try {
    const next = [char, ...readRecent().filter((item) => item !== char)].slice(0, RECENT_CAP);
    window.localStorage.setItem(RECENT_KEY, JSON.stringify(next));
  } catch {
    // Blocked storage (private mode, quota): recency is a nicety, not state.
  }
}
