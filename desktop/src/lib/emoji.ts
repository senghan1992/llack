/**
 * Emoji data for the picker, the reaction chooser and `:shortcode:` completion.
 *
 * Hand-curated rather than a 4,000-entry Unicode dump: a workplace uses a few
 * hundred emoji, and every one of those needs *Korean* keywords — "좋아요",
 * "확인", "회의" — or search is useless for the people this product is for.
 * Codes follow the GitHub/Slack shortcode convention so `:+1:` typed from
 * habit keeps working. No runtime dependency; the file is the data.
 *
 * Sequences are written as escapes where the glyph needs a variation selector
 * (U+FE0F) or a ZWJ, so an editor cannot silently drop them.
 */

